"""Create a uiter iteration workspace.

Usage:
    python3 scripts/new_iteration.py <iteration-id> --screenshot PATH --repo PATH
        [--mode polish|restructure|reinvent] [--focus "component name"] [--constraints "text"]
        [--models PRESET] [--scorer MODEL] [--inventor MODEL] [--improver MODEL]

Creates <skill-root>/workspace/<iteration-id>/ with this layout:

    original/screenshot.png      copied from --screenshot (the original)
    original/target.txt          absolute path of the target repo, from --repo
    original/brief.json          the design brief: mode, focus, constraints, models per role
    scores/                      filled by haiku scorers, one <group-id>.json each (5, from metrics/groups.json)
    improved/                    filled by the fable implementer (changes.diff, notes.md)
    judgement.md                 generated by scripts/score.py, never hand-edited

--html is deprecated: isolated HTML reproductions are no longer used. It is still
accepted so older invocations keep working; the file is copied to original/legacy.html.

Refuses to reuse an existing iteration id so earlier runs are never overwritten.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

SKILL_ROOT = Path(__file__).resolve().parent.parent
MODES = ("polish", "restructure", "reinvent")
ROLES = ("scorer", "inventor", "improver")
MODELS_FILE = SKILL_ROOT / "models.json"


def resolve_models(preset, overrides):
    """Return ({role: model}, preset name) from models.json plus per-role overrides."""
    config = json.loads(MODELS_FILE.read_text(encoding="utf-8"))
    preset = preset or config["default_preset"]
    if preset not in config["presets"]:
        raise ValueError(f"unknown --models preset '{preset}'; choose from {', '.join(config['presets'])}")
    models = dict(config["presets"][preset])
    for role, model in overrides.items():
        if model:
            if model not in config["models"]:
                raise ValueError(f"unknown model '{model}' for --{role}; choose from {', '.join(config['models'])}")
            models[role] = model
    return models, preset


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("iteration_id", help="folder name for this iteration, e.g. login-card-01")
    parser.add_argument("--screenshot", type=Path, required=True, help="path to the original screenshot (png/jpg)")
    parser.add_argument("--repo", type=Path, help="absolute path of the target project the fable implementer edits")
    parser.add_argument("--mode", choices=MODES, default="reinvent",
                        help="how far the redesign may go (default reinvent, the full redesign): polish (refine in place), restructure "
                             "(rework layout from root causes), reinvent (design from scratch, divergent concepts)")
    parser.add_argument("--focus", default="",
                        help="optional: the one component or region to work on, e.g. 'history table'; empty = whole screen")
    parser.add_argument("--constraints", default="",
                        help="optional: what must not change or is off limits, in the user's words")
    parser.add_argument("--models", default="",
                        help="model preset from models.json (default, all-haiku, all-fable, opus-build)")
    for role in ROLES:
        parser.add_argument(f"--{role}", default="", help=f"model for the {role} role; overrides the preset")
    parser.add_argument("--html", type=Path, help="deprecated: legacy isolated HTML, kept for old invocations")
    args = parser.parse_args()

    if not args.iteration_id.replace("-", "").replace("_", "").isalnum():
        print("error: iteration id may only contain letters, digits, '-' and '_'", file=sys.stderr)
        return 2

    if not args.screenshot.is_file():
        print(f"error: screenshot not found: {args.screenshot}", file=sys.stderr)
        return 2

    repo = None
    if args.repo is not None:
        repo = args.repo.expanduser().resolve()
        if not (repo / ".git").exists():
            print(f"error: --repo is not a git repository: {repo}", file=sys.stderr)
            return 2

    try:
        models, preset = resolve_models(args.models, {r: getattr(args, r) for r in ROLES})
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.html is not None and not args.html.is_file():
        print(f"error: html not found: {args.html}", file=sys.stderr)
        return 2

    iteration = SKILL_ROOT / "workspace" / args.iteration_id
    if iteration.exists():
        print(f"error: {iteration} already exists; choose a new iteration id", file=sys.stderr)
        return 2

    for sub in ("original", "scores", "improved"):
        (iteration / sub).mkdir(parents=True)

    shutil.copyfile(args.screenshot, iteration / "original" / f"screenshot{args.screenshot.suffix.lower()}")

    if repo is not None:
        (iteration / "original" / "target.txt").write_text(str(repo) + "\n", encoding="utf-8")

    brief = {
        "mode": args.mode,
        "focus": args.focus.strip(),
        "constraints": args.constraints.strip(),
        "preset": preset,
        "models": models,
    }
    (iteration / "original" / "brief.json").write_text(json.dumps(brief, indent=2) + "\n", encoding="utf-8")

    if args.html is not None:
        print("warning: --html is deprecated; copied to original/legacy.html and not used by the skill", file=sys.stderr)
        shutil.copyfile(args.html, iteration / "original" / "legacy.html")

    focus = f", focus: {brief['focus']}" if brief["focus"] else ", focus: whole screen"
    roles = ", ".join(f"{r}={m}" for r, m in models.items())
    print(f"created {iteration} (mode: {brief['mode']}{focus}; models: {preset}: {roles})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
